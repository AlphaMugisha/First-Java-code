public class PetHealthRecord {
    public static void main(String[] args) {
        // Bobby's health record using appropriate data types
        String name = "Bobby";       // String for text
        int age = 4;                 // int for whole numbers
        double weight = 12.5;        // double for decimal numbers
        char size = 'M';             // char for single character
        boolean vaccinated = true;   // boolean for true/false

        // Printing each value with a clear label
        System.out.println("--- Pet Health Record ---");
        System.out.println("Pet Name: " + name);
        System.out.println("Age: " + age + " years");
        System.out.println("Weight: " + weight + " kg");
        System.out.println("Size: " + size);
        System.out.println("Vaccinated: " + vaccinated);
    }
}
